# Quartic residue symbols and Gauss sums over Z[i].
# Gaussian integers as Python complex with integer parts, or tuples (a,b).
import cmath, math
from functools import lru_cache

def gmul(x,y): return (x[0]*y[0]-x[1]*y[1], x[0]*y[1]+x[1]*y[0])
def gnorm(x): return x[0]*x[0]+x[1]*x[1]
def gconj(x): return (x[0],-x[1])
def gdivmod(x,y):
    # nearest-integer division in Z[i]
    n=gnorm(y); num=gmul(x,gconj(y))
    q=(round(num[0]/n), round(num[1]/n))
    r=(x[0]-gmul(q,y)[0], x[1]-gmul(q,y)[1])
    return q,r
def gmod(x,y): return gdivmod(x,y)[1]
def gpow_mod(x,e,m):
    r=(1,0); x=gmod(x,m)
    while e:
        if e&1: r=gmod(gmul(r,x),m)
        x=gmod(gmul(x,x),m); e>>=1
    return r
UNITS=[(1,0),(0,1),(-1,0),(0,-1)]
def is_primary(n):
    # n = a+bi primary iff n ≡ 1 mod (2+2i) i.e. (a,b) ≡ (1,0) or (3,2) mod 4
    a,b=n[0]%4,n[1]%4
    return (a,b) in ((1,0),(3,2))
def primary_assoc(n):
    for u in UNITS:
        m=gmul(u,n)
        if is_primary(m): return m
    return None

def factor_norm(N):
    f={}; d=2
    while d*d<=N:
        while N%d==0: f[d]=f.get(d,0)+1; N//=d
        d+=1
    if N>1: f[N]=f.get(N,0)+1
    return f

@lru_cache(None)
def primary_prime_over(p):
    # for p ≡ 1 mod 4 return the two primary primes over p; for p≡3 mod 4 return (-p) primary
    if p%4==3:
        return (primary_assoc((p,0)),)
    for a in range(1,int(p**0.5)+1):
        b2=p-a*a; b=int(round(b2**0.5))
        if b*b==b2:
            return (primary_assoc((a,b)), primary_assoc((a,-b)))
    raise ValueError

def gfactor(n):
    """factor primary odd n into primary primes (with multiplicity). returns list of primes"""
    N=gnorm(n); res=[]; rem=n
    for p,e in factor_norm(N).items():
        if p==2: raise ValueError("not odd")
        for pi in primary_prime_over(p):
            while True:
                q,r=gdivmod(rem,pi)
                if r==(0,0): res.append(pi); rem=q
                else: break
    return res

I4=[1,1j,-1,-1j]
def chi_prime(a,pi):
    """quartic residue symbol (a/pi)_4 for primary prime pi; 0 if pi|a"""
    if gmod(a,pi)==(0,0): return 0
    Np=gnorm(pi)
    v=gpow_mod(a,(Np-1)//4,pi)
    for k,u in enumerate(UNITS):
        if gmod((v[0]-u[0],v[1]-u[1]),pi)==(0,0): return I4[k]
    raise ValueError("no unit match")

def chi(a,n,fac=None):
    if fac is None: fac=gfactor(n)
    r=1
    for pi in fac:
        r*=chi_prime(a,pi)
        if r==0: return 0
    return r

def residues(n):
    """complete residue system mod n (n Gaussian integer)"""
    N=gnorm(n); res=[]
    # use box enumeration and reduce; pick canonical reps
    seen=set()
    R=int(math.isqrt(N))+2
    # lattice: Z[i]/nZ[i] has N elements; enumerate x in box [0,N) x [0,1)? simpler: a+bi with 0<=a<N, b=0..? 
    # Z[i]/n ≅ Z/N only if gcd(a,b)=1 for n=a+bi. General: use Hermite basis.
    a,b=n
    # lattice nZ[i] generated by n=(a,b) and i*n=(-b,a). Find HNF basis.
    import itertools
    v1=(a,b); v2=(-b,a)
    # HNF of matrix rows v1,v2 over Z: columns (real, imag)
    M=[[a,b],[-b,a]]
    # compute HNF via gcd on first column
    def ext_gcd(x,y):
        if y==0: return (abs(x), (1 if x>=0 else -1), 0)
        g,s,t=ext_gcd(y,x%y); return (g,t,s-(x//y)*t)
    g,s,t=ext_gcd(M[0][0],M[1][0])
    r1=[s*M[0][0]+t*M[1][0], s*M[0][1]+t*M[1][1]]
    # second row: combination killing first col
    c1=M[1][0]//g if g else 0; c0=M[0][0]//g if g else 0
    r2=[-c1*M[0][0]+c0*M[1][0], -c1*M[0][1]+c0*M[1][1]]
    assert r2[0]==0
    d1=abs(r1[0]); d2=abs(r2[1])
    assert d1*d2==N, (d1,d2,N)
    return [(x,y) for x in range(d1) for y in range(d2)]

def gauss(n,j=1,h=(1,0),fac=None):
    """g_j(h,n)=sum_{x mod n} chi_n(x)^j psi(h x/n), psi(z)=exp(2 pi i Im z)"""
    if fac is None: fac=gfactor(n)
    N=gnorm(n); s=0
    nc=gconj(n)
    for x in residues(n):
        c=chi(x,n,fac)
        if c==0: continue
        hx=gmul(h,x); z=gmul(hx,nc)  # hx/n = hx*conj(n)/N
        s+=c**j*cmath.exp(2j*math.pi*z[1]/N)
    return s

def mobius(fac):
    return 0 if len(set(fac))<len(fac) else (-1)**len(fac)
